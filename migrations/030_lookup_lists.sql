-- Admin "Listas" tab: three lookup lists whose tables were never created, so adding to them failed with
-- "Could not find the table 'public.immigration_statuses' in the schema cache".
--   immigration_statuses  → Situação Imigratória (member form)
--   expense_categories    → Categorias de Despesa (Tesouraria)
--   income_types          → Tipos de Entrada (Tesouraria)
-- Same shape as the existing `categories` / `functions` lists. They start with the values the app already
-- used as built-in fallbacks, so nothing changes on screen. Additive and idempotent.

CREATE TABLE IF NOT EXISTS immigration_statuses (
  id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text        NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 1 AND 80),
  sort_order integer     NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS expense_categories (
  id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text        NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 1 AND 80),
  sort_order integer     NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS income_types (
  id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text        NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 1 AND 80),
  sort_order integer     NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE immigration_statuses DISABLE ROW LEVEL SECURITY;
GRANT ALL PRIVILEGES ON immigration_statuses TO anon, authenticated, service_role;

ALTER TABLE expense_categories DISABLE ROW LEVEL SECURITY;
GRANT ALL PRIVILEGES ON expense_categories TO anon, authenticated, service_role;

ALTER TABLE income_types DISABLE ROW LEVEL SECURITY;
GRANT ALL PRIVILEGES ON income_types TO anon, authenticated, service_role;

